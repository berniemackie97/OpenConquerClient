    public static RgbaImage Load(string iconId) =>
        TryGetIndex(iconId, out int index) ? EmbeddedMedia.Load(s_icons[index])
            : throw new ArgumentException("Unsupported bundled server icon identifier.", nameof(iconId));

    /// <summary>Identifiers are exactly <c>gNNsMM</c>: a 1-based group and a server within that group.</summary>
    private static bool TryGetIndex(string? iconId, out int index)
    {
        index = -1;
        if (iconId is not { Length: 6 } || iconId[0] != 'g' || iconId[3] != 's' ||
            !char.IsAsciiDigit(iconId[1]) || !char.IsAsciiDigit(iconId[2]) || !char.IsAsciiDigit(iconId[4]) || !char.IsAsciiDigit(iconId[5]))
        {
            return false;
        }

        int group = (iconId[1] - '0') * 10 + iconId[2] - '0';
        int server = (iconId[4] - '0') * 10 + iconId[5] - '0';
        if (group < 1 || group > s_serversPerGroup.Length || server < 1 || server > s_serversPerGroup[group - 1])
        {
            return false;
        }

        index = server - 1;
        for (int previous = 0; previous < group - 1; previous++)
        {
            index += s_serversPerGroup[previous];
        }

        return true;
    }
