    [Fact]
    public void Modulus_MatchesVerifiedNativeSeedTransform()
    {
        Assert.Equal(256, s_verifiedNativeSeed.Length);

        uint[] seedWords = new uint[64];

        for (int index = 0; index < seedWords.Length; index++)
        {
            seedWords[index] = BinaryPrimitives.ReadUInt32LittleEndian(
                s_verifiedNativeSeed.AsSpan(index * sizeof(uint), sizeof(uint))
            );
        }

        uint[] schedule = new uint[64];

        for (int index = 0; index < 63; index++)
        {
            schedule[(0x11 + index) & 0x3F] = seedWords[index] ^ seedWords[index + 1];
        }

        schedule[(0x11 + 63) & 0x3F] = 0x2220F2A7;

        byte[] derivedModulus = new byte[256];

        for (int index = 0; index < schedule.Length; index++)
        {
            BinaryPrimitives.WriteUInt32BigEndian(
                derivedModulus.AsSpan(index * sizeof(uint), sizeof(uint)),
                schedule[index]
            );
        }

        Assert.Equal(ServerDatNativePublicKey.Modulus.ToArray(), derivedModulus);
    }

    [Fact]
    public void Modulus_MatchesVerifiedNativeSha256AndExponent()
    {
        byte[] digest = SHA256.HashData(ServerDatNativePublicKey.Modulus);

        Assert.Equal(
            "76ACB04B08190B129985F8DEE2B466EFCD686EB1662CB598BD1A8154CB9196F1",
            Convert.ToHexString(digest)
        );

        Assert.Equal(0x1_0001, ServerDatNativePublicKey.PublicExponent);
    }
